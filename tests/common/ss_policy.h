/*
	What the single-step vectors are good for, file by file and vector by vector.

	The vectors were generated by an emulator (Reicast's interpreter on an ARM64 host), not by a console. They
	record no access widths, they execute everything without exceptions and their FPU results are the host's.
	The per-file table carries what the files do not say (access widths, instruction class) and what is known
	to fail on devcast and why. The filter takes out, with a reason, the vectors that cannot be run or whose
	expected result is not what an SH4 does. Nothing else is skipped.
*/
#pragma once
#include "ss_format.h"

enum SsFilterReason
{
	SSF_NONE,			//the vector is run
	SSF_UNALIGNED,		//data access at an address that is not a multiple of its width
	SSF_ODD_PC,			//instruction fetch from an odd address
	SSF_FPU_DISABLED,	//FPU instruction with SR.FD=1
	SSF_PRIVILEGED,		//privileged instruction with SR.MD=0
	SSF_TRAPA_NOP,		//TRAPA, recorded as a nop
	SSF_HOST_NAN,		//the expected FPU result is the generator host's NaN
	SSF_FPSCR_BITS,		//the expected FPSCR has bits that an SH4 does not implement

	SSF_COUNT
};

//SsFilePolicy::flags
#define SSP_FPU			0x0001	//FPU instruction: FPU disable exception when SR.FD=1
#define SSP_PRIVILEGED	0x0002	//privileged instruction: illegal in user mode
#define SSP_TRAPA		0x0004	//TRAPA
#define SSP_FP_RESULT	0x0008	//FP arithmetic: a NaN result has a host specific encoding
#define SSP_FTRC		0x0010	//FTRC: the result for a NaN is host specific
#define SSP_DOUBLE		0x0020	//FP operands are doubles (DRn = FR[2n]:FR[2n+1])
#define SSP_MAY_CRASH	0x0040	//known defect that ends in die()/verify(), see known

struct SsFilePolicy
{
	const char* file;		//file name without SS_FILE_SUFFIX
	const char* mnemonic;
	u8 read_size;			//width in bytes of the data read, 0: the instruction does not read
	u8 write_size;			//width in bytes of the data write, 0: the instruction does not write
	u16 flags;				//SSP_*
	const char* known;		//why vectors of this file are known not to pass, 0: all of them are expected to
};

//The policy of a vector file, 0 if the file is not in the table
const SsFilePolicy* ss_policy_find(const std::string& file);

//Number of files in the table
u32 ss_policy_count();
const SsFilePolicy* ss_policy_at(u32 index);

//Why a vector is not run, SSF_NONE if it is. When more than one reason applies it is the first in the order an
//SH4 would notice them: the instruction, its data access, the next fetch. ignore is a mask of reasons
//(1 << SSF_x) that are left out
SsFilterReason ss_policy_filter(const SsFilePolicy& policy, const SsTest& test, u32 ignore = 0);

//The notification devcast is known to raise on a vector and to carry on from: the text of the msgboxf, 0 if
//there is none. Any other notification is a defect
const char* ss_policy_notification(const SsFilePolicy& policy, const SsTest& test);

const char* ss_filter_name(SsFilterReason reason);
const char* ss_filter_description(SsFilterReason reason);
